"""Use pydantic models as fields of DRF serializers"""

from typing import Any

from drf_spectacular.extensions import OpenApiSerializerFieldExtension
from drf_spectacular.plumbing import ResolvedComponent
from pydantic import BaseModel, TypeAdapter
from pydantic import ValidationError as PydanticValidationError
from rest_framework.exceptions import ValidationError
from rest_framework.fields import JSONField


class PydanticField(JSONField):
    """DRF field which validates its value with a pydantic model, and stores it as JSON.

    `named_unions` maps component names to (discriminated) union types used within the model.
    In the OpenAPI schema, those unions are registered as their own component and referenced,
    instead of being repeated inline."""

    def __init__(
        self, model: type[BaseModel], named_unions: dict[str, Any] | None = None, **kwargs
    ):
        self.model = model
        self.named_unions = named_unions or {}
        super().__init__(**kwargs)

    def to_internal_value(self, data: Any) -> dict:
        try:
            return self.model.model_validate(data).model_dump(mode="json")
        except PydanticValidationError as exc:
            raise ValidationError(
                [
                    f"{'.'.join(str(part) for part in error['loc'])}: {error['msg']}"
                    for error in exc.errors(include_url=False)
                ]
            ) from exc


class PydanticFieldExtension(OpenApiSerializerFieldExtension):
    target_class = "authentik.lib.pydantic.PydanticField"
    match_subclasses = True
    ref_template = "#/components/schemas/{model}"

    def map_serializer_field(self, auto_schema, direction):
        field: PydanticField = self.target
        schema = field.model.model_json_schema(ref_template=self.ref_template)
        definitions = {**schema.pop("$defs", {}), field.model.__name__: schema}
        for name, union in field.named_unions.items():
            union_schema = TypeAdapter(union).json_schema(ref_template=self.ref_template)
            union_schema.pop("$defs", None)
            ref = {"$ref": self.ref_template.format(model=name)}
            definitions = {
                key: self.replace(value, union_schema, ref) for key, value in definitions.items()
            }
            definitions[name] = union_schema
        for name, definition in definitions.items():
            auto_schema.registry.register_on_missing(
                ResolvedComponent(
                    name=name,
                    type=ResolvedComponent.SCHEMA,
                    object=f"pydantic-{name}",
                    schema=self.to_openapi_3_0(definition),
                )
            )
        return {"$ref": self.ref_template.format(model=field.model.__name__)}

    def replace(self, schema: Any, needle: dict, replacement: dict) -> Any:
        """Recursively replace occurrences of `needle` in `schema`"""
        if isinstance(schema, list):
            return [self.replace(item, needle, replacement) for item in schema]
        if not isinstance(schema, dict):
            return schema
        if {key: value for key, value in schema.items() if key != "title"} == needle:
            return replacement
        return {key: self.replace(value, needle, replacement) for key, value in schema.items()}

    def to_openapi_3_0(self, schema: Any) -> Any:
        """Convert a JSON schema generated by pydantic (draft 2020-12) to OpenAPI 3.0:
        `const` becomes a single-value `enum`, `anyOf` with `null` becomes `nullable`,
        and titles are removed so generated clients name types after their components."""
        if isinstance(schema, list):
            return [self.to_openapi_3_0(item) for item in schema]
        if not isinstance(schema, dict):
            return schema
        schema = {
            key: self.to_openapi_3_0(value)
            for key, value in schema.items()
            if not (key == "title" and isinstance(value, str))
        }
        if "const" in schema:
            schema["enum"] = [schema.pop("const")]
        if {"type": "null"} in schema.get("anyOf", []):
            others = [item for item in schema.pop("anyOf") if item != {"type": "null"}]
            if len(others) > 1:
                schema["anyOf"] = others
            elif "$ref" in others[0]:
                schema["allOf"] = others
            else:
                schema.update(others[0])
            schema["nullable"] = True
        return schema
