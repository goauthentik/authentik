"""Use pydantic models as fields of DRF serializers"""

from typing import Any

from drf_spectacular.extensions import OpenApiSerializerFieldExtension
from drf_spectacular.plumbing import ResolvedComponent
from pydantic import BaseModel, TypeAdapter
from pydantic import ValidationError as PydanticValidationError
from rest_framework.exceptions import ValidationError
from rest_framework.fields import JSONField

OPENAPI_REF_TEMPLATE = "#/components/schemas/{model}"


def format_pydantic_errors(exc: PydanticValidationError) -> list[str]:
    """Convert pydantic validation errors to a list of messages including their location"""
    messages = []
    for error in exc.errors(include_url=False):
        location = ".".join(str(part) for part in error["loc"])
        messages.append(f"{location}: {error['msg']}" if location else error["msg"])
    return messages


def to_openapi_3_0(schema: Any) -> Any:
    """Convert a JSON schema generated by pydantic (draft 2020-12) to OpenAPI 3.0:
    `const` becomes a single-value `enum`, `anyOf` with `null` becomes `nullable`,
    and titles are removed so generated clients name types after their components."""
    if isinstance(schema, list):
        return [to_openapi_3_0(item) for item in schema]
    if not isinstance(schema, dict):
        return schema
    schema = {
        key: to_openapi_3_0(value)
        for key, value in schema.items()
        if not (key == "title" and isinstance(value, str))
    }
    if "const" in schema:
        schema["enum"] = [schema.pop("const")]
    any_of = schema.get("anyOf")
    if isinstance(any_of, list) and {"type": "null"} in any_of:
        others = [item for item in any_of if item != {"type": "null"}]
        del schema["anyOf"]
        if len(others) == 1 and "$ref" not in others[0]:
            schema.update(others[0])
        elif len(others) == 1:
            schema["allOf"] = others
        else:
            schema["anyOf"] = others
        schema["nullable"] = True
    return schema


class PydanticField(JSONField):
    """DRF field which validates its value with a pydantic model, and stores it as JSON.

    `named_unions` maps component names to (discriminated) union types used within the model.
    In the OpenAPI schema, those unions are registered as their own component and referenced,
    instead of being repeated inline."""

    def __init__(
        self,
        model: type[BaseModel],
        named_unions: dict[str, Any] | None = None,
        **kwargs,
    ):
        self.model = model
        self.named_unions = named_unions or {}
        super().__init__(**kwargs)

    def to_internal_value(self, data: Any) -> dict:
        try:
            validated = self.model.model_validate(data)
        except PydanticValidationError as exc:
            raise ValidationError(format_pydantic_errors(exc)) from exc
        return validated.model_dump(mode="json")

    def to_representation(self, value: Any) -> Any:
        if isinstance(value, BaseModel):
            return value.model_dump(mode="json")
        return value

    def json_schema(self, ref_template: str) -> tuple[dict, dict[str, dict]]:
        """JSON schema of the model and a dict of definitions it references"""
        schema = self.model.model_json_schema(ref_template=ref_template)
        definitions = schema.pop("$defs", {})
        for name, union in self.named_unions.items():
            union_schema = TypeAdapter(union).json_schema(ref_template=ref_template)
            union_schema.pop("$defs", None)
            ref = {"$ref": ref_template.format(model=name)}
            schema = _replace(schema, union_schema, ref)
            definitions = {
                key: _replace(value, union_schema, ref) for key, value in definitions.items()
            }
            definitions[name] = union_schema
        return schema, definitions


def _replace(schema: Any, needle: dict, replacement: dict) -> Any:
    """Recursively replace occurrences of `needle` in `schema`"""
    if isinstance(schema, dict):
        stripped = {key: value for key, value in schema.items() if key != "title"}
        if stripped == needle:
            return replacement
        return {key: _replace(value, needle, replacement) for key, value in schema.items()}
    if isinstance(schema, list):
        return [_replace(item, needle, replacement) for item in schema]
    return schema


class PydanticFieldExtension(OpenApiSerializerFieldExtension):
    target_class = "authentik.lib.pydantic.PydanticField"
    match_subclasses = True

    def map_serializer_field(self, auto_schema, direction):
        field: PydanticField = self.target
        schema, definitions = field.json_schema(OPENAPI_REF_TEMPLATE)
        definitions[field.model.__name__] = schema
        for name, definition in definitions.items():
            auto_schema.registry.register_on_missing(
                ResolvedComponent(
                    name=name,
                    type=ResolvedComponent.SCHEMA,
                    object=f"pydantic-{name}",
                    schema=to_openapi_3_0(definition),
                )
            )
        return {"$ref": OPENAPI_REF_TEMPLATE.format(model=field.model.__name__)}
